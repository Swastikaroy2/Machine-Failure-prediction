"""### EDA conclusions (write these in your report)
- The data has no missing values and no duplicate rows.
- `UDI` and `Product ID` are unique for every row, so they are identifiers and are dropped.
- Failures are rare (about 3.4%), so recall/precision/F1 of the failure class matter more than accuracy.
- Failures are linked to high tool wear, extreme torque/speed combinations and a small temperature difference, which is why feature engineering is helpful.

## Section 3: Prepare the data
**What:**
1. Rename columns to simple names.
2. **Drop** identifiers (`UDI`, `Product ID`) and the failure-mode flags (`TWF, HDF, PWF, OSF, RNF`) to **prevent data leakage**.
3. **Feature engineering** (new columns computed only from the input sensors, never from the target):
   - `Temp_diff` = process temp - air temp (heat dissipation)
   - `Power_W` = torque x angular speed (mechanical power)
   - `Wear_Torque` = tool wear x torque (overstrain)
   - optional domain features (if `USE_DOMAIN_FEATURES = True`): `Overstrain_ratio` (wear x torque divided by the limit of that machine Type), `Low_heat_flag` (small temperature difference and low speed), `Power_out_of_range` (power too low or too high)
4. One-hot encode `Type` and standardise the numbers (inside a pipeline).

**Expected output:** a clean feature table with no target leakage.
"""

df = df_raw.rename(columns={
    "Air temperature [K]": "Air_temp", "Process temperature [K]": "Process_temp",
    "Rotational speed [rpm]": "Rot_speed", "Torque [Nm]": "Torque",
    "Tool wear [min]": "Tool_wear", "Machine failure": "Failure"})

leak_cols = ["UDI", "Product ID", "TWF", "HDF", "PWF", "OSF", "RNF"]
df = df.drop(columns=leak_cols)

WEAR_LIMIT = {"L": 11000, "M": 12000, "H": 13000}   # overstrain limits from the dataset documentation

def add_features(d):
    d = d.copy()
    d["Temp_diff"] = d["Process_temp"] - d["Air_temp"]
    d["Power_W"] = d["Torque"] * d["Rot_speed"] * 2 * np.pi / 60
    d["Wear_Torque"] = d["Tool_wear"] * d["Torque"]
    if USE_DOMAIN_FEATURES:
        d["Overstrain_ratio"] = d["Wear_Torque"] / d["Type"].map(WEAR_LIMIT)
        d["Low_heat_flag"] = ((d["Temp_diff"] < 8.6) & (d["Rot_speed"] < 1380)).astype(int)
        d["Power_out_of_range"] = ((d["Power_W"] < 3500) | (d["Power_W"] > 9000)).astype(int)
    return d

y = df["Failure"]
X = add_features(df.drop(columns="Failure"))

cat_cols = ["Type"]
num_cols = [c for c in X.columns if c not in cat_cols]
print("Number of features:", X.shape[1])
print("Features used:", list(X.columns))
print("Leakage columns removed:", leak_cols)
display(X.head())

def make_preprocessor():
    return ColumnTransformer([
        ("cat", OneHotEncoder(handle_unknown="ignore"), cat_cols),
        ("num", StandardScaler(), num_cols)])

"""## Section 4: Split into training and test data
**What:** 80% of the rows train the model, 20% are kept hidden for the final test. `stratify=y` keeps the same failure percentage in both parts.
**Expected output:** 8,000 training rows and 2,000 test rows with equal failure rates.
"""

X_train, X_test, y_train, y_test = train_test_split(X, y, test_size=0.2, stratify=y, random_state=RS)
print("Train:", X_train.shape, "| Test:", X_test.shape)
print("Failures in train: %d (%.3f%%) | in test: %d (%.3f%%)" %
      (y_train.sum(), y_train.mean()*100, y_test.sum(), y_test.mean()*100))

"""## Section 5: Train the three classification models
**What:** train Logistic Regression, Decision Tree and Random Forest with default settings as a **baseline**.
`class_weight="balanced"` makes the models pay more attention to the rare failure class.
**Expected output:** three trained models.
"""

models = {
    "Logistic Regression": LogisticRegression(max_iter=3000, class_weight="balanced", random_state=RS),
    "Decision Tree": DecisionTreeClassifier(class_weight="balanced", random_state=RS),
    "Random Forest": RandomForestClassifier(n_estimators=300, class_weight="balanced", n_jobs=-1, random_state=RS),
}
pipes = {n: Pipeline([("prep", make_preprocessor()), ("model", m)]) for n, m in models.items()}

for n, p in pipes.items():
    t0 = time.time(); p.fit(X_train, y_train)
    print(f"Trained: {n:20s} ({time.time()-t0:.1f}s)")

"""## Section 6: Evaluate and compare the baseline models
**What:** measure each model on the test set with accuracy, precision, recall and F1.
- **Precision (fail):** of the machines predicted to fail, how many really failed.
- **Recall (fail):** of the machines that really failed, how many were caught.
- **F1 (fail):** balance of precision and recall.

**Expected output:** a comparison table and one confusion matrix per model.
"""

def metric_row(name, model, Xe, ye):
    p = model.predict(Xe)
    return {"Model": name, "Accuracy": accuracy_score(ye, p), "Precision (fail)": precision_score(ye, p),
            "Recall (fail)": recall_score(ye, p), "F1 (fail)": f1_score(ye, p)}

base_table = pd.DataFrame([metric_row(n, p, X_test, y_test) for n, p in pipes.items()]).set_index("Model").round(4)
print("BASELINE results on the test set")
display(base_table)

"""### Confusion matrix 1: Logistic Regression (baseline)
**Reading it:** top-left = healthy correctly identified, bottom-right = failures caught, bottom-left = **missed failures**, top-right = false alarms.
"""

ConfusionMatrixDisplay(confusion_matrix(y_test, pipes["Logistic Regression"].predict(X_test)),
                       display_labels=["No fail", "Fail"]).plot(cmap="Blues")
plt.title("Logistic Regression (baseline)"); plt.show()

"""### Confusion matrix 2: Decision Tree (baseline)"""

ConfusionMatrixDisplay(confusion_matrix(y_test, pipes["Decision Tree"].predict(X_test)),
                       display_labels=["No fail", "Fail"]).plot(cmap="Blues")
plt.title("Decision Tree (baseline)"); plt.show()

"""### Confusion matrix 3: Random Forest (baseline)"""

ConfusionMatrixDisplay(confusion_matrix(y_test, pipes["Random Forest"].predict(X_test)),
                       display_labels=["No fail", "Fail"]).plot(cmap="Blues")
plt.title("Random Forest (baseline)"); plt.show()

"""## Section 7: Cross-validation
**What:** instead of trusting one split, the training data is cut into 5 folds. Each fold is used once for validation while the other 4 train the model. This shows how **consistent** each model is.
**Expected output:** five F1 scores and their average for every model.
"""

skf = StratifiedKFold(n_splits=5, shuffle=True, random_state=RS)
cv_rows = []
for n, p in pipes.items():
    s = cross_val_score(clone(p), X_train, y_train, cv=skf, scoring="f1", n_jobs=-1)
    print(f"{n:20s} 5 fold scores: {np.round(s, 4)} | mean = {s.mean():.4f} (+/- {s.std():.4f})")
    cv_rows.append({"Model": n, "Fold 1": s[0], "Fold 2": s[1], "Fold 3": s[2], "Fold 4": s[3], "Fold 5": s[4],
                    "Mean CV F1": s.mean(), "Std": s.std()})
display(pd.DataFrame(cv_rows).set_index("Model").round(4))

"""### 7b: Repeated cross-validation (more reliable)
**What:** the same 5-fold test repeated 3 times with different shuffles (15 scores per model). A small standard deviation means the model is stable.
"""

rskf = RepeatedStratifiedKFold(n_splits=5, n_repeats=3, random_state=RS)
rep_rows = []
for n, p in pipes.items():
    s = cross_val_score(clone(p), X_train, y_train, cv=rskf, scoring="f1", n_jobs=-1)
    print(f"{n:20s} mean F1 over 15 folds = {s.mean():.4f} (+/- {s.std():.4f})")
    rep_rows.append({"Model": n, "Mean F1 (15 folds)": s.mean(), "Std": s.std(), "Min": s.min(), "Max": s.max()})
display(pd.DataFrame(rep_rows).set_index("Model").round(4))

"""## Section 8: Hyperparameter tuning with GridSearchCV
**What:** hyperparameters are settings chosen before training (tree depth, number of trees, regularisation). GridSearchCV tries every combination in a grid using 5-fold cross-validation and keeps the combination with the best **F1-score**. The grids below are larger than a basic run, which means **more training** and usually better results.
**Expected output:** the best settings and best cross-validation F1 for each model.
"""

param_grids = {
    "Logistic Regression": {"model__C": [0.01, 0.1, 0.5, 1, 5, 10, 50, 100],
                            "model__class_weight": ["balanced", None]},
    "Decision Tree": {"model__max_depth": [3, 5, 7, 10, 15, None],
                      "model__min_samples_leaf": [1, 2, 5, 10, 20],
                      "model__criterion": ["gini", "entropy"],
                      "model__class_weight": ["balanced", None]},
    "Random Forest": {"model__n_estimators": [300],
                      "model__max_depth": [10, None],
                      "model__min_samples_leaf": [1, 3],
                      "model__max_features": ["sqrt", 0.6],
                      "model__class_weight": ["balanced_subsample", None]},
}
tuned = {}

def run_grid(name):
    t0 = time.time()
    gs = GridSearchCV(clone(pipes[name]), param_grids[name], scoring="f1", cv=skf, n_jobs=-1, refit=True)
    gs.fit(X_train, y_train)
    tuned[name] = gs
    print(f"{name}\n  Combinations tried: {len(gs.cv_results_['params'])}"
          f"\n  Best params : {gs.best_params_}\n  Best CV F1  : {gs.best_score_:.4f}"
          f"\n  Time        : {time.time()-t0:.0f}s")

"""### 8.1 Tune Logistic Regression"""

run_grid("Logistic Regression")

"""### 8.2 Tune Decision Tree"""

run_grid("Decision Tree")

"""### 8.3 Tune Random Forest
This is the slowest cell (a few minutes). Please wait for it to finish.
"""

run_grid("Random Forest")

"""### 8.4 Tuning summary
**Expected output:** one table with the best hyperparameters and best CV score of each model.
"""

tune_table = pd.DataFrame([{"Model": n, "Best CV F1": g.best_score_,
                            "Best params": {k.replace("model__", ""): v for k, v in g.best_params_.items()}}
                           for n, g in tuned.items()]).set_index("Model")
tune_table["Best CV F1"] = tune_table["Best CV F1"].round(4)
pd.set_option("display.max_colwidth", 200)
