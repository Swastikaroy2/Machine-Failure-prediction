def add_features(d, domain=True):
    d = d.copy()
    d["Temp_diff"] = d["Process_temp"] - d["Air_temp"]
    d["Power_W"] = d["Torque"] * d["Rot_speed"] * 2 * np.pi / 60
    d["Wear_Torque"] = d["Tool_wear"] * d["Torque"]
    if domain:
        d["Overstrain_ratio"] = d["Wear_Torque"] / d["Type"].map(WEAR_LIMIT)
        d["Low_heat_flag"] = ((d["Temp_diff"] < 8.6) & (d["Rot_speed"] < 1380)).astype(int)
        d["Power_out_of_range"] = ((d["Power_W"] < 3500) | (d["Power_W"] > 9000)).astype(int)
    return d

